#!/usr/bin/env python3
"""Refresh bootstrap's additive release modules from the canonical migrations."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
schema = root / '设计/schema.sql'
marker = '-- BEGIN ADDITIVE RELEASE MODULES (generated by tools/build_schema.py)'
base = schema.read_text().split(marker, 1)[0].rstrip()
modules = sorted(p for p in (root / '设计/migrations').glob('*.sql')
                 if p.name[:3].isdigit() and int(p.name[:3]) >= 3 and 'preflight' not in p.stem)
schema.write_text(base + '\n\n' + marker + '\n' + '\n'.join(
    '\n-- Source: migrations/' + p.name + '\n' + p.read_text() for p in modules))
print('Bootstrap synchronized with {} additive migrations.'.format(len(modules)))
